-- =====================================================
-- Наш ключ гифки прямо во вложении сообщения.
--
-- Сообщение хранит ссылку на нашу запись каталога (gif_key = gif_catalog.gif_uuid),
-- а не только на внешний URL. Это разделяет сообщение и источник гифки: каталог
-- (и, при выносе, gif-сервис) можно менять независимо, а рендер не зависит от
-- того, где живёт каталог.
-- =====================================================

ALTER TABLE attachments ADD COLUMN gif_key UUID;
CREATE INDEX idx_attachments_gif_key ON attachments(gif_key);
