-- =====================================================
-- Email — идентичность единого IdP (auth-service), chat его не хранит.
--
-- Раньше chat держал локальную копию email, и при привязке аккаунта по
-- username она не обновлялась — профиль показывал устаревший email, отличный
-- от того, которым пользователь входит. Теперь email в chat отсутствует:
-- профиль берёт его из auth-service (/auth/me), поэтому расхождение невозможно.
-- =====================================================

-- Уникальное ограничение users_email_key и его индекс удалятся вместе с колонкой.
ALTER TABLE users
    DROP COLUMN IF EXISTS email,
    DROP COLUMN IF EXISTS email_verified;
